def normalize_messages(raw_messages):
    transformed = []
    for message in raw_messages or []:
        role = message.get("role", "user")
        if role not in {"user", "assistant"}:
            continue

        text = (message.get("text") or "").strip()
        attachments = message.get("attachments") or []

        blocks = []
        if text:
            blocks.append({"type": "text", "text": text})

        for attachment in attachments:
            kind = attachment.get("type")
            if kind == "image":
                data_url = attachment.get("dataUrl") or ""
                if not data_url.startswith("data:"):
                    continue
                header, _, encoded = data_url.partition(",")
                mime_type = "image/png"
                if ";base64" in header:
                    mime_type = header.split(":", 1)[1].split(";", 1)[0]
                try:
                    image_data = base64.b64decode(encoded)
                except Exception:
                    continue
                blocks.append(
                    {
                        "type": "image",
                        "source": {
                            "type": "base64",
                            "media_type": mime_type,
                            "data": base64.b64encode(image_data).decode("utf-8"),
                        },
                    }
                )

        transformed.append({"role": role, "content": blocks or [{"type": "text", "text": "..."}]})

    return transformed


def extract_text_from_messages(messages):
    text_messages = []
    for item in messages:
        role = item.get("role")
        if role not in {"user", "assistant"}:
            continue
        text_parts = []
        text = (item.get("text") or "").strip()
        if text:
            text_parts.append(text)
        attachments = item.get("attachments") or []
        for attachment in attachments:
            if attachment.get("type") == "image":
                text_parts.append("[Hình ảnh đính kèm]")
        if text_parts:
            text_messages.append({"role": role, "content": "\n".join(text_parts)})
    return text_messages


def model_provider(model_name):
    name = (model_name or "").lower()
    if name.startswith("gemini"):
        return "gemini"
    if name.startswith("deepseek"):
        return "deepseek"
    if name.startswith("gpt") or name.startswith("o1") or name.startswith("o3"):
        return "openai"
    if name.startswith("claude"):
        return "anthropic"
    return "openai"


def call_gemini(model_name, messages):
    api_key = GEMINI_API_KEY
    if not api_key:
        raise RuntimeError("Missing GEMINI_API_KEY")

    model_names = [model_name]

    last_error = None
    for candidate_model in model_names:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{candidate_model}:generateContent?key={api_key}"
        payload = {
            "systemInstruction": {"parts": [{"text": build_system_prompt()}]},
            "contents": [],
            "generationConfig": {"maxOutputTokens": 768, "temperature": 0.5},
        }
        for message in extract_text_from_messages(messages):
            payload["contents"].append({
                "role": "user" if message["role"] == "user" else "model",
                "parts": [{"text": message["content"]}],
            })

        try:
            response = httpx.post(url, json=payload, timeout=60.0)
            response.raise_for_status()
            result = response.json()
            candidates = result.get("candidates") or []
            for candidate in candidates:
                parts = candidate.get("content", {}).get("parts", [])
                if parts:
                    text = "".join(part.get("text", "") for part in parts if isinstance(part, dict))
                    if text:
                        return text.strip()
            raise RuntimeError("Gemini response did not contain text")
        except httpx.HTTPStatusError as exc:
            last_error = exc
            if exc.response.status_code != 404:
                raise
    raise last_error if last_error else RuntimeError("Gemini request failed")


def call_deepseek(model_name, messages):
    api_key = DEEPSEEK_API_KEY
    if not api_key:
        raise RuntimeError("Missing DEEPSEEK_API_KEY")

    response = httpx.post(
        "https://api.deepseek.com/v1/chat/completions",
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
        json={
            "model": model_name,
            "messages": [
                {"role": "system", "content": build_system_prompt()},
                *[{"role": item["role"], "content": item["content"]} for item in extract_text_from_messages(messages)],
            ],
            "stream": False,
        },
        timeout=60.0,
    )
    response.raise_for_status()
    result = response.json()
    choices = result.get("choices") or []
    if not choices:
        raise RuntimeError("DeepSeek returned no choices")
    message = choices[0].get("message", {})
    return (message.get("content") or "").strip() or "Tôi không có phản hồi rõ ràng cho yêu cầu này."


