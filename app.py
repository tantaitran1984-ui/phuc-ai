@app.route("/api/history", methods=["GET", "PUT"])
@login_required
def account_history():
    user_id = session["user_id"]
    if request.method == "GET":
        with database_connection() as connection:
            row = execute_query(
                connection,
                "SELECT sessions_json FROM user_history WHERE user_id = ?",
                (user_id,),
            ).fetchone()
        try:
            sessions = json.loads(row["sessions_json"]) if row else []
        except (TypeError, json.JSONDecodeError):
            sessions = []
        return jsonify({"sessions": sessions})

    data = request.get_json(silent=True) or {}
    sessions = data.get("sessions")
    if not isinstance(sessions, list):
        return jsonify({"error": "Lịch sử hội thoại không hợp lệ."}), 400

    sessions_json = json.dumps(sessions, ensure_ascii=False, separators=(",", ":"))
    if len(sessions_json.encode("utf-8")) > 14 * 1024 * 1024:
        return jsonify({"error": "Lịch sử quá lớn để sao lưu."}), 413

    with database_connection() as connection:
        execute_query(
            connection,
            """
            INSERT INTO user_history (user_id, sessions_json, updated_at)
            VALUES (?, ?, CURRENT_TIMESTAMP)
            ON CONFLICT(user_id) DO UPDATE SET
                sessions_json = excluded.sessions_json,
                updated_at = CURRENT_TIMESTAMP
            """,
            (user_id, sessions_json),
        )
    return jsonify({"saved": True})


