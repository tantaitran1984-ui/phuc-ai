def start_user_session(user):
    session.clear()
    session["user_id"] = user["id"]
    session.permanent = True
    return jsonify({"authenticated": True, "username": user["username"]})


@app.post("/api/auth/register")
def register():
    data = request.get_json(silent=True) or {}
    username = str(data.get("username") or "").strip()
    password = data.get("password") or ""

    if not re.fullmatch(r"[\w.-]{3,32}", username, flags=re.UNICODE):
        return jsonify({"error": "Tên đăng nhập cần dài 3-32 ký tự, chỉ gồm chữ, số, dấu chấm, gạch ngang hoặc gạch dưới."}), 400
    if not isinstance(password, str) or not 8 <= len(password) <= 128:
        return jsonify({"error": "Mật khẩu cần dài từ 8 đến 128 ký tự."}), 400

    try:
        with database_connection() as connection:
            cursor = execute_query(
                connection,
                "INSERT INTO users (username, password_hash) VALUES (?, ?) RETURNING id",
                (username, generate_password_hash(password)),
            )
            user = {"id": cursor.fetchone()["id"], "username": username}
            execute_query(connection, "INSERT INTO user_history (user_id) VALUES (?)", (user["id"],))
    except Exception as exc:
        if isinstance(exc, sqlite3.IntegrityError) or exc.__class__.__name__ == "UniqueViolation":
            return jsonify({"error": "Tên đăng nhập này đã được sử dụng."}), 409
        raise

    return start_user_session(user), 201


@app.post("/api/auth/login")
def login():
    data = request.get_json(silent=True) or {}
    username = str(data.get("username") or "").strip()
    password = data.get("password") or ""

    with database_connection() as connection:
        user = execute_query(
            connection,
            "SELECT id, username, password_hash FROM users WHERE username = ?",
            (username,),
        ).fetchone()

    if not user or not isinstance(password, str) or not check_password_hash(user["password_hash"], password):
        return jsonify({"error": "Tên đăng nhập hoặc mật khẩu không đúng."}), 401
    return start_user_session(user)


@app.get("/api/auth/me")
def current_user():
    user_id = session.get("user_id")
    if not user_id:
        return jsonify({"authenticated": False})

    with database_connection() as connection:
        user = execute_query(
            connection,
            "SELECT username FROM users WHERE id = ?",
            (user_id,),
        ).fetchone()
    if not user:
        session.clear()
        return jsonify({"authenticated": False})
    return jsonify({"authenticated": True, "username": user["username"]})


